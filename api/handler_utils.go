// we are getting symbols from frontend and here we convert them into ids for that we need this funciton
func (apiCgf *APIConfig) ResolveSymbols(r *http.Request) ([]int32, error) {
	symbolsParam := r.URL.Query().Get("symbols")
	if symbolsParam == "" {
		return nil, errors.New("missing symbols")
	}

	// 1. Split the comma-separated string into a slice
	// e.g., "AAPL,MSFT" -> []string{"AAPL", "MSFT"}
	symbolsList := strings.Split(symbolsParam, ",")

	// 2. Call the database function generated by sqlc
	stockIDs, err := apiCgf.DB.GetStockIdsBySymbols(r.Context(), symbolsList)
	if err != nil {
		return nil, err
	}

	// 3. (Optional but recommended) Check if any symbols were invalid
	if len(stockIDs) != len(symbolsList) {
		return nil, errors.New("one or more symbols were not found in the database")
	}

	return stockIDs, nil
}

// We created this functions as we are using all this in every routing file.

// Read about  in about.txt point 15
type CalcFunc[T any] func(prices []float64, dates []time.Time) (T, error)

func HandleCalcRequest[T any](apiCgf *APIConfig, w http.ResponseWriter, r *http.Request, fn CalcFunc[T]) {

	prices, dates, err := apiCgf.HandlerFetchPrice(r)
	if err != nil {
		httputils.ResponseWithError(w, 400, err.Error())
		return
	}
	if len(prices) == 0 || len(dates) == 0 {
		httputils.ResponseWithError(w, 400, "no price data")
		return
	}

	result, err := fn(prices, dates)
	if err != nil {
		httputils.ResponseWithError(w, 400, err.Error())
		return
	}

	httputils.ResponseWithJSON(w, 200, result)
}

func (apiCgf *APIConfig) HandlerFetchPrice(r *http.Request) ([]float64, []time.Time, error) {
	//parse dates from r (user input)
	stockIDs, err := apiCgf.ResolveSymbols(r)
	if err != nil {
		return nil, nil, err
	}
	startDateStr := r.URL.Query().Get("start_date")
	endDateStr := r.URL.Query().Get("end_date")

	// handling date errors
	startDate, endDate, err := HandlerQueryParams(startDateStr, endDateStr)
	if err != nil {
		return nil, nil, err
	}

	if len(stockIDs) == 0 {
		return nil, nil, errors.New("no valid stock IDs found for the given symbols")
	}
	//fix the returned format for the adjusted_col to float array/slice so that we can call the periodiccalcreturn func with it
	dbPrices, err := apiCgf.DB.GetDailyPricesByStockInDateRange(r.Context(),
		internaldb.GetDailyPricesByStockInDateRangeParams{
			StockID:       stockIDs[0],
			FromTradeDate: startDate,
			ToTradeDate:   endDate,
		})
	if err != nil {
		return nil, nil, err
	}
	// do return json using the model.go file.
	cvDbPrices, dbDates := db.DatabasePricesToFloatsAndDates(dbPrices)
	if len(cvDbPrices) == 0 || len(dbDates) == 0 {
		return nil, nil, errors.New("no price data found in the specified date range")
	}

	return cvDbPrices, dbDates, nil
}

func HandlerQueryParams(startDateStr, endDateStr string) (time.Time, time.Time, error) {

	//1. empty strings
	if startDateStr == "" || endDateStr == "" {
		return time.Time{}, time.Time{}, errors.New("missing start date, or end date")
	}

	//2. Right dates passed

	//what is layout read in about.txt 13
	reference_layout := "2006-01-02" // Standard YYYY-MM-DD format

	startDate, err := time.Parse(reference_layout, startDateStr)
	if err != nil {
		return time.Time{}, time.Time{}, errors.New("start_date Input Invalid")

	}
	endDate, err := time.Parse(reference_layout, endDateStr)
	if err != nil {
		return time.Time{}, time.Time{}, errors.New("end_date Input Invalid")
	}
	//if start_date is after end_date
	if startDate.After(endDate) {
		return time.Time{}, time.Time{}, errors.New("start_date cannot be higher then end_date")
	}
	return startDate, endDate, nil
}
